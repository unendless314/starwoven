const RANK_ZH = ['一', '二', '三', '四', '五', '六', '七', '八', '九', '十', '侍者', '騎士', '皇后', '國王'];
const RANK_EN = ['Ace', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten', 'Page', 'Knight', 'Queen', 'King'];

const pad = (n: number) => String(n).padStart(2, '0');

export const CARDS: TarotCard[] = [
  ...MAJORS.map(([nameZh, nameEn, upright, reversed], i) => ({
    id: `major-${pad(i)}`,
    nameZh,
    nameEn,
    arcana: 'major' as const,
    suit: null,
    upright,
    reversed,
    image: null,
  })),
  ...SUITS.flatMap(({ suit, nameZh, nameEn, cards }) =>
    cards.map(([upright, reversed], i) => ({
      id: `${suit}-${pad(i + 1)}`,
      nameZh: `${nameZh}${RANK_ZH[i]}`,
      nameEn: `${RANK_EN[i]} of ${nameEn}`,
      arcana: 'minor' as const,
      suit,
      upright,
      reversed,
      image: null,
    })),
  ),
];

const CARD_MAP = new Map(CARDS.map((card) => [card.id, card]));

export function getCard(id: string): TarotCard | undefined {
  return CARD_MAP.get(id);
}
